"""inject_numbers.py — emit manuscript/numbers.tex (panel constants only).

Retired in v11.0. Earlier versions of this script injected the metric-race,
basket-ES and placebo outputs of the superseded Sigma-space design. That design
was replaced by the pair-level gradient test (scripts/estimator_gradient.py,
whose output lives in manuscript/numbers_gradient.tex), so those macros are no
longer emitted: a numbers file full of values for an analysis the paper no
longer contains is a reproducibility defect, not a record of it.

What remains here are the two panel constants the text cites. Both are derived
from data rather than typed in.

Reads:  data/panel_summary.csv, scripts/_common.py (EVENTS)
Writes: manuscript/numbers.tex
"""
from __future__ import annotations

import sys
from pathlib import Path

import pandas as pd

BASE = Path(__file__).resolve().parent.parent
DATA = BASE / "data"
OUT = BASE / "manuscript" / "numbers.tex"

sys.path.insert(0, str(BASE / "scripts"))
from _common import EVENTS  # noqa: E402


def main() -> None:
    summary_fp = DATA / "panel_summary.csv"
    if not summary_fp.exists():
        raise SystemExit("data/panel_summary.csv missing — run aggregate_panel.py first.")
    summary = pd.read_csv(summary_fp)

    lines = ["%% AUTOGENERATED by scripts/inject_numbers.py — do not edit by hand."]

    def add(name: str, val: object) -> None:
        lines.append(rf"\newcommand{{\{name}}}{{{val}}}")

    # Number of stablecoins with daily coverage dense enough to enter the panel.
    add("NPANEL", len(summary))
    # Number of documented de-peg events carried by the panel.
    add("NEVENTS", len(EVENTS))

    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"-> {OUT}")
    print(f"   NPANEL={len(summary)}  NEVENTS={len(EVENTS)}")


if __name__ == "__main__":
    main()
